"""Emit the shared enums as TypeScript so the web app never hard-codes a state string.

    python -m enola.scripts.export_enums web/src/lib/enums.generated.ts
"""

from __future__ import annotations

import sys
from pathlib import Path

from enola.core.enums import ALL_ENUMS


def render() -> str:
    lines = ["// GENERATED by `python -m enola.scripts.export_enums` — do not edit.", ""]
    for enum in ALL_ENUMS:
        lines.append(f"export const {enum.__name__} = {{")
        for member in enum:
            lines.append(f'  {member.name}: "{member.value}",')
        lines.append("} as const;")
        lines.append(f"export type {enum.__name__} = (typeof {enum.__name__})[keyof typeof {enum.__name__}];")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    target = Path(sys.argv[1] if len(sys.argv) > 1 else "web/src/lib/enums.generated.ts")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(), encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
